"""Build site/index.html and THESIS.md from data/derived/ only. No network access."""
import json, re
from pathlib import Path
import pandas as pd
import plotly.graph_objects as go
from plotly.subplots import make_subplots

M = json.loads(Path("data/derived/metrics.json").read_text())
D = pd.read_csv("data/derived/daily.csv", parse_dates=["date"]).set_index("date")


def get(path):
    v = M
    for k in path.split("."):
        v = v[int(k)] if isinstance(v, list) else v[k]
    return v


def fmt(v):
    if isinstance(v, float) and v.is_integer() and abs(v) >= 1000:
        v = int(v)
    if isinstance(v, int):
        return f"{v:,}"
    return str(v)


def render(tmpl):
    """Replace {{a.b.c}} with values from metrics.json. Unknown keys fail the build."""
    return re.sub(r"\{\{([\w.\-]+)\}\}", lambda m: fmt(get(m.group(1))), tmpl)


def chart_index():
    m = D[["near_price", "txns", "active_accounts", "gas_used"]].rolling(30).mean().resample("W").last()
    m = m[m.index >= "2021-01-01"]
    base = m.max()
    f = go.Figure()
    names = {"near_price": "NEAR price", "txns": "Transactions / day", "active_accounts": "Active accounts / day",
             "gas_used": "Gas used / day (consensus data)"}
    for c, n in names.items():
        f.add_scatter(x=m.index, y=100 * m[c] / base[c], name=n, mode="lines")
    f.update_layout(title="Each series as % of its own all-time high (30-day average)", yaxis_title="% of peak",
                    height=430, margin=dict(l=40, r=20, t=50, b=40), legend=dict(orientation="h"))
    return f


def chart_value():
    s = D["mcap_to_fees"].resample("W").last()
    s = s[s.index >= "2021-01-01"]
    f = go.Figure(go.Scatter(x=s.index, y=s, mode="lines", name="market cap / annualised fees"))
    f.update_layout(title="Market cap ÷ annualised network fees (log scale): how much of the price fees can explain",
                    yaxis_type="log", height=380, margin=dict(l=40, r=20, t=50, b=40))
    return f


def table(rows, cols):
    h = "".join(f"<th>{c}</th>" for c in cols)
    b = "".join("<tr>" + "".join(f"<td>{fmt(r.get(c, ''))}</td>" for c in cols) + "</tr>" for r in rows)
    return f"<table><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table>"


def main():
    thesis_md = render(Path("THESIS.tmpl.md").read_text())
    Path("THESIS.md").write_text("<!-- generated by build.py from THESIS.tmpl.md; do not edit by hand -->\n" + thesis_md)
    corr = [{"period": k, **v} for k, v in M["correlations_monthly_log_change"].items()]
    rpc = [{"date": k, **{kk: vv for kk, vv in v.items() if kk != "top_receivers"},
            "top app (share of sampled txns)": f'{v["top_parents"][0]["parent"]} ({v["top_parents"][0]["share_pct"]}%)' if v["top_parents"] else ""}
           for k, v in M["rpc_crosscheck"].items()]
    from markdown_it import MarkdownIt
    body = MarkdownIt("commonmark").enable("table").render(thesis_md.split("\n", 1)[1] if thesis_md.startswith("<!--") else thesis_md)
    c1 = chart_index().to_html(full_html=False, include_plotlyjs="cdn", div_id="chart-index")
    c2 = chart_value().to_html(full_html=False, include_plotlyjs=False, div_id="chart-value")
    shocks = table(M["usage_shocks"], ["date", "txns_pct", "gas_pct", "accounts_pct", "price_pct"])
    ctab = table(corr, ["period", "txns", "active_accounts", "gas_used", "weeks"])
    rtab = table(rpc, ["date", "sampled_blocks", "rpc_est_signed_txns_day", "indexer_txns_day", "indexer_over_rpc", "top app (share of sampled txns)"]) if rpc else "<p>No RPC samples in this snapshot.</p>"
    html = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Usage vs Price: NEAR</title><style>
body{{font:16px/1.55 system-ui,sans-serif;max-width:980px;margin:2rem auto;padding:0 1rem;color:#111}}
table{{border-collapse:collapse;margin:1rem 0;font-size:14px}}td,th{{border:1px solid #ccc;padding:4px 8px;text-align:right}}
th{{background:#f3f3f3}}code{{background:#f3f3f3;padding:1px 4px}}.note{{color:#555;font-size:14px}}</style></head><body>
<p class="note">Snapshot {M["range"]["first_day"]} → {M["range"]["last_day"]} ({M["range"]["days"]:,} days). Every number on this page is computed by
<code>metrics.py</code> from the frozen raw files listed in <code>data/MANIFEST.sha256</code>. Rebuild: <code>make all</code>.</p>
{body.replace("<h2>Evidence for</h2>", c1 + "<h2>Evidence for</h2>", 1)}
<h2>Charts and tables</h2>
{c2}
<h3>Correlation of ~monthly log changes vs NEAR price (weekly samples)</h3>{ctab}
<h3>Largest one-day transaction shocks since 2022 (% change)</h3>{shocks}
<h3>Independent check: archival RPC sample vs indexer</h3>{rtab}
<p class="note">Sources: NearBlocks public API (<code>/v1/charts</code>, <code>/v1/account/intents.near/txns/count</code>), NEAR archival RPC. Not investment advice.</p>
</body></html>"""
    Path("site").mkdir(exist_ok=True)
    Path("site/index.html").write_text(html)
    print("built site/index.html and THESIS.md")


if __name__ == "__main__":
    main()
